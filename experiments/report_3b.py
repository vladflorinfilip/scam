"""Build the Qwen2.5-3B vs 0.5B comparison report from committed artifacts."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "data/experiments"
RULES = ["s1", "voice", "clause", "lexical", "lexical_e6"]
BASE_RULE = {"lexical_e6": "lexical"}
FOLLOW_05B_FREE = {"s1": 0.98, "voice": 0.99, "clause": 0.97}  # Claude rescoring of 0.5B adapter outputs


FINDINGS = """## Key findings (interpretation of the tables below)

1. **Training.** With the matched recipe s1, voice and clause install at 3B as strongly as at 0.5B (99.5–100% paired follow, 94–99% critic-scored free-generation follow). Lexical does not (57.7% vs 50% base); a 6-epoch adapter (`lexical_e6`, off-recipe) reaches 100% paired / 99% free-generation follow.
2. **Depth.** Rank-1 own-rule ablation has no effect at layers 0–25 for any rule. Effects appear only near the output: s1 at L31–34 (strongest L32), voice uniformly at L27–35, clause and lexical_e6 only at the final block L35. At 0.5B the same method removed every rule at L20–22 of 24, so at 3B the rules sit relatively later and, for clause and lexical, at a single final layer.
3. **Removal vs. collapse.** At 3B the effective layers mostly collapse the answer to one label instead of restoring base behaviour: voice L27–35 and s1 L32 make the model answer 0 almost always (predicts-1 ≈ 0%); clause and lexical_e6 at L35 push it to 1 (predicts-1 85–87%). Only s1 reaches base-rate follow with ≥95% base preservation on the held-out pairs (L34: 99.5% → 54.0%, preservation 97.5%), and even there predicts-1 is 4%. At 0.5B voice also collapsed (1%), while s1 did not (51.5%) but cost more base behaviour (81% preservation).
4. **Selection consequence.** Effective voice and clause layers preserve <95% of base answers on the selection set, so the full scan falls back to a base-safe but ineffective layer (L26). For lexical_e6, L35 (53% drop, preservation shown as 95.0%) was not selected because its preservation is just below the 0.95 threshold. Late-window scans (L30–33) force a late layer and show the same pattern.
5. **Controls.** Five random directions never change follow for any rule, scan or transfer arm.
6. **Free generation.** Ablating the selected s1 direction (L34) cuts critic-scored rule following in free generation from 95% to 27%. For voice, clause and lexical_e6 the selected layers were ineffective on pairs and are also ineffective in free generation (94→94%, 98→94%, 99→98%). The strong-but-damaging layers (voice L27–35, clause/lexical L35) were not free-generation tested.
7. **Transfer at L30.** No shared rank passed the source criteria. The rank-8 consensus subspace partially suppresses s1 (→60–65%) and voice (→60–65%) but not clause or lexical, with 85–92% base preservation. Mean-direction cosines: s1–voice 0.60, clause ≈0.33 with both, lexical ≈0 with all. s1 and voice share part of a direction at 3B; clause and lexical are separate.

"""


def load(path):
    path = Path(path)
    return json.loads(path.read_text()) if path.exists() else None


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}%"


def scan(kind, rule):
    names = {
        "full": f"3b_full/{rule}_residual_scan_3b_full",
        "late": f"3b_late_l30plus/{rule}_residual_scan_l30plus",
        "late05": f"late_l20plus/{rule}_residual_scan_l20plus",
    }
    d = D / "residuals/scans" / names[kind]
    exp, summ, layers = load(d / "experiment.json"), load(d / "summary.json"), load(d / "layer_scan.json")
    if not (exp and summ):
        return None
    s = summ[BASE_RULE.get(rule, rule)]
    rand = [v["follow"] for k, v in s.items() if k.startswith("random_")]
    best = max(layers, key=lambda k: layers[k]["follow_drop"]) if layers else None
    return {"exp": exp, "sel": s["selected"], "rand_min_follow": min(rand) if rand else None,
            "layers": layers, "best": best, "dir": d}


def row(rule, kind, label):
    r = scan(kind, rule)
    if not r:
        return f"| {rule} | {label} | not available |||||||\n"
    s, e = r["sel"], r["exp"]
    best = r["best"]
    b = r["layers"][best] if best else {}
    return (f"| {rule} | {label} | L{e['selected_layer']} ({'pass' if e['selection_base_control_passed'] else 'fail'}) "
            f"| {pct(s['unablated_follow'])} → {pct(s['follow'])} | {pct(s['base_follow'])} | {pct(s['base_preservation'])} "
            f"| {pct(s['predicts_1'])} | {pct(r['rand_min_follow'])} | L{best}: drop {pct(b.get('follow_drop'))}, pres {pct(b.get('base_preservation'))} |\n")


def main():
    out = ["# Qwen2.5-3B replication of the 0.5B steganographic-rule experiments\n\n",
           "Generated by `experiments/report_3b.py` from artifacts on branch `3b-tests`. "
           "Same data, splits, LoRA recipe (r8/α16, lr 2e-4, 3 epochs) and analysis code as 0.5B. "
           "`lexical_e6` is an off-recipe 6-epoch lexical adapter, trained because the matched recipe did not install the lexical rule. "
           "Critic: claude-opus-5-5 (calibrated against the 0.5B gpt-4.1 labels: clause 100%, voice 99%, s1 93% agreement); lexical is scored deterministically.\n\n",
           FINDINGS,
           "## 1. Training success\n\n",
           "Held-out fixed-CoT pairs: fraction of answers that follow the hidden rule. Free generation: 100 ETHICS prompts, critic-scored rule adherence of the adapter (base 3B never emits a parseable final answer, so its free-generation rate is 0).\n\n",
           "| Rule | 3B adapter (pairs) | 3B base (pairs) | 0.5B adapter (pairs) | 0.5B base (pairs) | 3B adapter free-gen follow | 0.5B adapter free-gen follow |\n|---|---|---|---|---|---|---|\n"]
    for rule in RULES:
        p = load(D / f"baselines/3b/{rule}/paired_summary.json") or {}
        f = load(D / f"baselines/3b/{rule}/free_critic_summary.json") or {}
        r05 = scan("late05", BASE_RULE.get(rule, rule))
        s05 = r05["sel"] if r05 else {}
        out.append(f"| {rule} | {pct(p.get('follow'))} | {pct(p.get('base_follow'))} | {pct(s05.get('unablated_follow'))} | {pct(s05.get('base_follow'))} "
                   f"| {pct((f.get('adapter_unablated') or {}).get('follow_rate_all'))} | {pct(FOLLOW_05B_FREE.get(rule))} |\n")
    hdr = ("| Rule | Scan | Selected layer (base control) | Adapter follow: unablated → ablated | Base follow | Base preservation | Predicts 1 | Min follow over 5 random dirs | Strongest layer on selection set |\n"
           "|---|---|---|---|---|---|---|---|---|\n")
    out += ["\n## 2. Own-rule residual ablation (rank-1 mean direction, eval pairs)\n\n",
            "Selection (unchanged from 0.5B): per layer, fit on 50 pairs; on 30 separate selection pairs keep layers whose ablation preserves ≥95% of base answers ('base control pass'; if none, all layers are eligible) and pick the largest follow drop; evaluate on held-out pairs. So when the effective layers damage the base model on the selection set, the selected layer can be a weak but base-safe one. "
            "'Strongest layer' is the largest follow drop on the selection set regardless of the base control. Follow falling to the base rate means the rule is removed; "
            "check 'Predicts 1' (≈50% expected) for collapse to a single label.\n\n", hdr]
    for rule in RULES[:3] + ["lexical_e6"]:
        out.append(row(rule, "full", "3B full L0–35"))
        out.append(row(rule, "late", "3B late L30–33"))
        out.append(row(BASE_RULE.get(rule, rule), "late05", "0.5B late L20–22"))
    out.append("\n### Per-layer follow on the selection set (3B full scan)\n\n")
    layers = list(range(36))
    out.append("| Rule | " + " | ".join(f"L{l}" for l in layers) + " |\n|---|" + "---|" * len(layers) + "\n")
    for rule in RULES[:3] + ["lexical_e6"]:
        r = scan("full", rule)
        if r and r["layers"]:
            out.append(f"| {rule} | " + " | ".join(f"{100 * r['layers'][str(l)]['follow']:.0f}" if str(l) in r["layers"] else "–" for l in layers) + " |\n")
    out += ["\n## 3. Free generation under ablation (3B full-scan selected direction)\n\n",
            "| Rule | Adapter follow, unablated | Adapter follow, ablated | Critic errors (unablated / ablated) |\n|---|---|---|---|\n"]
    for rule in RULES[:3] + ["lexical_e6"]:
        r = scan("full", rule)
        f = load(r["dir"] / "free/free_critic_summary.json") if r else None
        if not f:
            out.append(f"| {rule} | not available | | |\n"); continue
        u, a = f.get("adapter_unablated", {}), f.get("adapter_selected", {})
        out.append(f"| {rule} | {pct(u.get('follow_rate_all'))} | {pct(a.get('follow_rate_all'))} | {u.get('critic_errors', 0)} / {a.get('critic_errors', 0)} |\n")
    out.append("\n## 4. Cross-rule transfer at layer 30 (shared consensus subspace, ranks 1/2/4/8)\n\n")
    for name in ("rules_s1-voice-clause_3b_l30", "four_rule_3b_l30_lexical_e6"):
        d = D / "residuals/transfer" / name
        sel, summ = load(d / "selection.json"), load(d / "summary.json")
        if not (sel and summ):
            out.append(f"**{name}**: not available.\n\n"); continue
        out.append(f"**{name}**: selected rank {sel['selected_rank']} ({'passed' if sel['passed'] else 'no rank passed'} source criteria: base preservation ≥95%, follow drop ≥20%, gap recovery ≥50% for every source).\n\n")
        out.append("| Target | Unablated | Shared subspace | Own subspace (same rank) | Min over 5 random | Base preservation (shared) | Predicts 1 (shared) |\n|---|---|---|---|---|---|---|\n")
        for rule, s in summ.items():
            rand = min(v["follow"] for k, v in s.items() if k.startswith("random_"))
            out.append(f"| {rule} | {pct(s['selected']['unablated_follow'])} | {pct(s['selected']['follow'])} | {pct(s['own']['follow'])} | {pct(rand)} "
                       f"| {pct(s['selected']['base_preservation'])} | {pct(s['selected']['predicts_1'])} |\n")
        geo = load(d / "direction_geometry.json")
        if geo:
            n = geo["names"]
            out.append("\nCosine similarity of rule mean directions:\n\n| | " + " | ".join(n) + " |\n|---|" + "---|" * len(n) + "\n")
            for a, cs in zip(n, geo["cosines"]):
                out.append(f"| {a} | " + " | ".join(f"{c:.2f}" for c in cs) + " |\n")
        out.append("\n")
    path = D / "report_3b_vs_05b.md"
    path.write_text("".join(out))
    print(path)


if __name__ == "__main__":
    main()
